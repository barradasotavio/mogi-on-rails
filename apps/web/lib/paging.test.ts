/** Replays wheel events, as [ms, deltaX, deltaY], through the listener on a 400 px pager: the pages it turns. */
function replay(t: TestContext, events: number[][]) {
  t.mock.timers.enable({ apis: ["setTimeout"] });
  let wheel: (event: unknown) => void = () => {};
  class Node {}
  const globals = globalThis as Record<string, unknown>;
  globals.Node = Node;
  globals.Element = class {};
  globals.WheelEvent = { DOM_DELTA_LINE: 1, DOM_DELTA_PAGE: 2 };
  globals.window = {
    setTimeout,
    addEventListener: (_: string, listener: typeof wheel) => (wheel = listener),
    removeEventListener: () => {},
  };
  const element = Object.assign(new Node(), { contains: () => true, clientWidth: 400 });
  const steps: number[] = [];
  const stop = listenForTrackpadPaging(element as unknown as HTMLElement, { onStep: (step) => steps.push(step) });
  let now = 0;
  for (const [time, deltaX, deltaY = 0] of events) {
    t.mock.timers.tick(time - now);
    now = time;
    wheel({ deltaX, deltaY, deltaMode: 0, ctrlKey: false, timeStamp: time, target: element, preventDefault() {} });
  }
  t.mock.timers.tick(1000);
  stop();
  return steps;
}

test("a fast Mac swipe turns one page, though its momentum carries merged events", (t) => {
  assert.deepEqual(replay(t, FAST_SWIPE), [1]);
});

test("a slow Mac swipe turns one page", (t) => {
  assert.deepEqual(replay(t, SLOW_SWIPE), [1]);
});

test("seven fast swipes turn seven pages, though each turn merges late events into one big delta", (t) => {
  assert.deepEqual(replay(t, SEVEN_SWIPES), [-1, -1, -1, 1, 1, 1, 1]);
});

test("swipes in quick succession turn a page each, as each one's fingers cut the previous momentum", (t) => {
  assert.deepEqual(replay(t, RAPID_SWIPES), [-1, -1, -1, -1]);
});

test("a vertical scroll that drifts sideways turns no page", (t) => {
  const scroll = Array.from({ length: 40 }, (_, i) => (i % 2 ? [i * 8, 2, 12] : [i * 8, 6, 2]));
  assert.deepEqual(replay(t, scroll), []);
});
